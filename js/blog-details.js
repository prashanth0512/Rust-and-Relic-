document.addEventListener('DOMContentLoaded', () => {

    const urlParams = new URLSearchParams(window.location.search);
    const blogId = urlParams.get('id');

    if (blogId && blogsData[blogId]) {
        renderBlog(blogsData[blogId]);
    } else {
        document.querySelector('.bd-main-container').innerHTML = `
            <div style="text-align:center; padding: 100px 0;">
                <h1 style="font-family: var(--bd-heading-font); color: var(--bd-text-primary);">Blog Post Not Found</h1>
                <a href="blogs.html" class="bd-btn" style="margin-top: 20px;">Return to Blogs</a>
            </div>
        `;
    }


});

function renderBlog(data) {
    document.getElementById('bd-title').innerText = data.title;
    document.getElementById('bd-author').innerText = data.author;
    document.getElementById('bd-date').innerText = data.date;
    document.getElementById('bd-featured-image').src = data.mainImage;
    document.getElementById('bd-featured-image').alt = data.title;

    document.getElementById('bd-intro').innerHTML = data.intro;
    document.getElementById('bd-main-content').innerHTML = data.mainContent;

    const tipsList = document.getElementById('bd-tips-list');
    tipsList.innerHTML = '';
    data.tips.forEach(tip => {
        tipsList.innerHTML += `<li>${tip}</li>`;
    });

    const imageGrid = document.getElementById('bd-image-grid');
    imageGrid.innerHTML = '';
    data.gallery.forEach(imgSrc => {
        imageGrid.innerHTML += `<img src="${imgSrc}" alt="${data.title} grid image">`;
    });

    document.getElementById('bd-conclusion').innerHTML = data.conclusion;
}
